import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildTenantIdentityGuardManifest } from './tenant-identity-guard-manifest.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'prisma/schema.prisma');
const baseMigrationPath = resolve(root, 'prisma/migrations/20261003000400_tenant_identity_immutability/migration.sql');
const previousExtensionMigrationPath = resolve(root, 'prisma/migrations/20261003000900_audit_tenant_identity_immutability/migration.sql');
const extensionMigrationDirectory = resolve(root, 'prisma/migrations/20261006000400_generic_saas_identity_guards');
const extensionMigrationPath = resolve(extensionMigrationDirectory, 'migration.sql');

function quoteIdentifier(value) {
  return '"' + value.replaceAll('"', '""') + '"';
}

function quoteLiteral(value) {
  return "'" + value.replaceAll("'", "''") + "'";
}

export function renderTenantIdentityGuardMigration(manifest) {
  const { schema, name, argumentTypes } = manifest.function;
  if (schema !== 'public' || argumentTypes.length !== 0) throw new Error('Unexpected tenant identity guard function contract');
  const functionName = 'public.' + quoteIdentifier(name);
  const functionRef = functionName + '()';
  const statements = [
    '-- Generated by scripts/generate-tenant-identity-guard-migration.mjs. Do not hand-edit.',
    '-- Tenant identity changes are rejected at the database boundary for every tenant-owned table.',
    'BEGIN;',
    'CREATE FUNCTION ' + functionRef + '\n' +
      'RETURNS trigger\n' +
      'LANGUAGE plpgsql\n' +
      'SET search_path = pg_catalog\n' +
      'AS $function$\n' +
      'DECLARE\n' +
      '  new_identity jsonb;\n' +
      '  old_identity jsonb;\n' +
      'BEGIN\n' +
      '  new_identity := pg_catalog.to_jsonb(NEW) -> TG_ARGV[0];\n' +
      '  old_identity := pg_catalog.to_jsonb(OLD) -> TG_ARGV[0];\n' +
      '  IF new_identity IS DISTINCT FROM old_identity THEN\n' +
      "    RAISE EXCEPTION 'tenant identity is immutable' USING ERRCODE = '42501';\n" +
      '  END IF;\n' +
      '  RETURN NEW;\n' +
      'END\n' +
      '$function$;',
    'REVOKE ALL ON FUNCTION ' + functionRef + ' FROM PUBLIC;',
  ];

  for (const trigger of manifest.triggers) {
    statements.push(
      'CREATE TRIGGER ' + quoteIdentifier(trigger.triggerName) +
        ' BEFORE UPDATE OF ' + quoteIdentifier(trigger.column) +
        ' ON public.' + quoteIdentifier(trigger.table) +
        ' FOR EACH ROW EXECUTE FUNCTION ' + functionName + '(' + quoteLiteral(trigger.column) + ');',
    );
  }
  statements.push('COMMIT;', '');
  return statements.join('\n');
}

export function renderTenantIdentityGuardExtensionMigration(manifest) {
  const { schema, name, argumentTypes } = manifest.function;
  if (schema !== 'public' || argumentTypes.length !== 0) throw new Error('Unexpected tenant identity guard function contract');
  const functionName = 'public.' + quoteIdentifier(name);
  const statements = [
    '-- Generated by scripts/generate-tenant-identity-guard-migration.mjs. Do not hand-edit.',
    '-- Forward-only immutable-tenant guards for tenant tables added after the base guard migration.',
    'BEGIN;',
  ];
  for (const trigger of manifest.triggers) {
    statements.push(
      'CREATE TRIGGER ' + quoteIdentifier(trigger.triggerName) +
        ' BEFORE UPDATE OF ' + quoteIdentifier(trigger.column) +
        ' ON public.' + quoteIdentifier(trigger.table) +
        ' FOR EACH ROW EXECUTE FUNCTION ' + functionName + '(' + quoteLiteral(trigger.column) + ');',
    );
  }
  statements.push('COMMIT;', '');
  return statements.join('\n');
}

function baseGuardedTables(sql) {
  const tables = [...sql.matchAll(/CREATE\s+TRIGGER\s+"(?:[^"]|"")*"[\s\S]*?\sON\s+public\."((?:[^"]|"")+)"/gi)]
    .map((match) => match[1].replaceAll('""', '"'));
  if (tables.length === 0 || new Set(tables).size !== tables.length) {
    throw new Error('The base tenant identity migration has an empty or duplicate trigger inventory');
  }
  return new Set(tables);
}

async function main() {
  const check = process.argv.includes('--check');
  const write = process.argv.includes('--write');
  if (check === write) throw new Error('Choose exactly one of --check or --write');
  const schema = await readFile(schemaPath, 'utf8');
  const manifest = buildTenantIdentityGuardManifest(schema);
  const baseSql = await readFile(baseMigrationPath, 'utf8');
  const baseTables = baseGuardedTables(baseSql);
  const availableTables = new Set(manifest.triggers.map((trigger) => trigger.table));
  for (const table of baseTables) {
    if (!availableTables.has(table)) throw new Error(`Base tenant identity migration references a table absent from the current schema: ${table}`);
  }
  const baseManifest = { ...manifest, triggers: manifest.triggers.filter((trigger) => baseTables.has(trigger.table)) };
  if (baseManifest.triggers.length !== baseTables.size) throw new Error('Base tenant identity migration trigger inventory is not represented by the current schema');
  const expectedBase = renderTenantIdentityGuardMigration(baseManifest);
  if (baseSql !== expectedBase) throw new Error('Base tenant identity migration differs from the immutable generated inventory');
  const previousExtensionSql = await readFile(previousExtensionMigrationPath, 'utf8');
  const previousExtensionTables = baseGuardedTables(previousExtensionSql);
  if ([...previousExtensionTables].some((table) => !availableTables.has(table) || baseTables.has(table))) {
    throw new Error('The previous forward tenant identity migration references an unknown or already guarded table');
  }
  const expectedPreviousExtension = renderTenantIdentityGuardExtensionMigration({
    ...manifest,
    triggers: manifest.triggers.filter((trigger) => previousExtensionTables.has(trigger.table)),
  });
  if (previousExtensionSql !== expectedPreviousExtension) throw new Error('Previous forward tenant identity migration differs from its immutable inventory');
  const guardedTables = new Set([...baseTables, ...previousExtensionTables]);
  const extensionManifest = { ...manifest, triggers: manifest.triggers.filter((trigger) => !guardedTables.has(trigger.table)) };
  const expectedExtension = renderTenantIdentityGuardExtensionMigration(extensionManifest);
  if (write) {
    await mkdir(extensionMigrationDirectory, { recursive: true });
    await writeFile(extensionMigrationPath, expectedExtension, 'utf8');
    console.log('Generated forward tenant identity guards for ' + extensionManifest.triggers.length + ' added tables.');
    return;
  }
  const currentExtension = await readFile(extensionMigrationPath, 'utf8');
  if (currentExtension !== expectedExtension) throw new Error('Forward tenant identity guards differ from the generated manifest.');
  console.log('Base and forward tenant identity migrations match the generated manifest.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : 'Tenant identity migration generation failed');
    process.exitCode = 1;
  }
}

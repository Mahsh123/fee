export function permissionsForRoles(roles: readonly RoleKey[]): string[] {
  const set = new Set<string>();
  for (const role of roles) {
    for (const permission of DEFAULT_ROLE_PERMISSIONS[role] ?? []) set.add(permission);
  }
  return [...set].sort();
}

export function roleHasPermission(role: RoleKey, permission: PermissionKey): boolean {
  return (DEFAULT_ROLE_PERMISSIONS[role] ?? []).includes(permission);
}
